"""Record tests/test_stories.yml from real conversations with a running bot.

Replays every scenario in tests/scenarios.yml through the REST channel,
prints the transcripts for review, and writes trimmed Rasa test stories:
user turns, actions, active loops, and slot events for slots that influence
dialogue prediction (bookkeeping slots like timestamps are dropped).

Usage (stack running, RASA_AUTH_TOKEN in .env):
    python3 scripts/record_test_stories.py               # writes tests/test_stories.yml
    python3 scripts/record_test_stories.py --dry-run     # transcripts only

Review every transcript before committing: a recorded story asserts that the
bot's current behaviour is correct.
"""
import argparse
import json
import time
import urllib.request
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
HEADER = (
    "# End-to-end test stories (run: rasa test core --stories tests/test_stories.yml)\n"
    "#\n"
    "# Generated by scripts/record_test_stories.py from tests/scenarios.yml, after\n"
    "# reviewing each transcript. Only slot events that influence dialogue\n"
    "# prediction are kept.\n\n"
)


def read_env() -> dict:
    env = {}
    for line in (ROOT / ".env").read_text().splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            key, value = line.split("=", 1)
            env[key.strip()] = value.strip()
    return env


def influencing_slots() -> set:
    domain = yaml.safe_load((ROOT / "domain.yml").read_text())
    return {
        name for name, slot in domain["slots"].items()
        if slot.get("influence_conversation", True) and slot.get("type") != "any"
    }


def send(base: str, sender: str, text: str) -> list:
    req = urllib.request.Request(
        f"{base}/webhooks/rest/webhook", method="POST",
        headers={"Content-Type": "application/json"},
        data=json.dumps({"sender": sender, "message": text}).encode(),
    )
    with urllib.request.urlopen(req, timeout=120) as resp:
        return [m.get("text", "") for m in json.load(resp)]


def tracker_story(base: str, sender: str, token: str) -> dict:
    url = f"{base}/conversations/{sender}/story?token={token}"
    with urllib.request.urlopen(url, timeout=30) as resp:
        (story,) = yaml.safe_load(resp.read().decode())["stories"]
    return story


def trim(steps: list, keep: set) -> list:
    out = []
    for step in steps:
        if "slot_was_set" in step:
            kept = [s for s in step["slot_was_set"] if next(iter(s)) in keep]
            if kept:
                out.append({"slot_was_set": kept})
        else:
            out.append(step)
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--url", default="http://localhost:5005")
    parser.add_argument("--scenarios", default=str(ROOT / "tests" / "scenarios.yml"))
    parser.add_argument("--out", default=str(ROOT / "tests" / "test_stories.yml"))
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    token = read_env()["RASA_AUTH_TOKEN"]
    keep = influencing_slots()
    scenarios = yaml.safe_load(Path(args.scenarios).read_text())["scenarios"]

    stories = []
    for i, sc in enumerate(scenarios):
        sender = f"record-{int(time.time() * 1000)}-{i}"
        print(f"=== {sc['name']}")
        for turn in sc["turns"]:
            print(f"  user: {turn}")
            for reply in send(args.url, sender, turn):
                print(f"   bot: {reply.strip()[:110]}")
        story = tracker_story(args.url, sender, token)
        stories.append({"story": sc["name"], "steps": trim(story["steps"], keep)})

    if args.dry_run:
        return
    body = yaml.safe_dump({"version": "3.1", "stories": stories}, sort_keys=False, allow_unicode=True, width=100)
    Path(args.out).write_text(HEADER + body)
    print(f"\nwrote {len(stories)} stories to {args.out}")


if __name__ == "__main__":
    main()
